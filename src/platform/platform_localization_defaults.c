bool platform_localization_default_find(const char *text, size_t length,
    platform_localization_default *out_entry)
{
    if (text == NULL || out_entry == NULL) return false;
    for (size_t index = 0U; index < sizeof(defaults) / sizeof(defaults[0]); ++index) {
        size_t fallback_length = strlen(defaults[index].fallback);
        if (fallback_length != length || memcmp(text, defaults[index].fallback, length) != 0)
            continue;
        *out_entry = defaults[index];
        return true;
    }
    return false;
}
