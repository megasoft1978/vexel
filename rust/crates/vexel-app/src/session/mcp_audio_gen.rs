//! `audio_generate` and `audio_envelope`.
//!
//! Generation runs in the optional helper process (see `audio_helper`): the
//! model-heavy work stays out of the app, nothing is fetched at render time
//! and a model download only happens when the caller passes `consent: true`.
//! The helper writes to a temporary file next to the target; the file is only
//! moved into place after it has been re-opened without following symlinks,
//! size-capped and header-checked, so the helper is never trusted with the
//! final path. With `addTrack` the file is added as an audio track in the same
//! undoable edit (a failed add removes the new file again).

