/// Requests one session may send to the helper.
pub const MAX_REQUESTS: u32 = 128;
/// Total generated bytes one session may keep.
pub const MAX_TOTAL_BYTES: u64 = 512 * 1024 * 1024;
/// Largest single generated file.
pub const MAX_FILE_BYTES: u64 = 32 * 1024 * 1024;
/// Longest generated clip.
pub const MAX_DURATION_MS: u64 = 120_000;
pub const VOICE_TIMEOUT: Duration = Duration::from_secs(120);
pub const OTHER_TIMEOUT: Duration = Duration::from_secs(60);
pub const MAX_PARAMS: usize = 24;

const NOT_WAV: &str = "audio_generate outPath must be a .wav file inside a granted directory";
const NEEDS_SAVE: &str = "audio_generate addTrack needs a saved document (save_as first) and an outPath inside its directory";
const OUTSIDE: &str = "audio_generate addTrack outPath must be inside the document's directory";
const NO_HELPER: &str = "audio helper not found; install tools/vexel-audio next to the app or set VEXEL_AUDIO_HELPER (see docs/audio.md)";
const BUDGET: &str = "audio generation budget for this session is used up (128 requests or 512 MiB); restart Vexel to reset it";
const MODEL_MISSING: &str = "audio_generate failed with model_missing: voice needs the Kokoro model and mlx-audio. Install: python3 -m pip install mlx-audio, then run tools/vexel-audio/vexel-audio --download-model (about 100 MB from huggingface.co/mlx-community/Kokoro-82M-4bit), or call audio_generate again with consent=true to download it now. Nothing is downloaded without consent.";
const BAD_PARAMS: &str = "audio helper rejected params: voice takes text (1-1000 chars), voice (Kokoro id such as af_heart), speed 0.5-2, effect (pip, whisper, soft) and pitchSemitones, bitcrushBits, tremoloHz, tremoloDepth, ringModHz, ringModMix, highpassHz, lowpassHz; sfx takes preset (whoosh, hum, launch, chime, siren, wind, comet, hoverbike), durationMs 200-15000, seed; music takes mood (adventure, calm, tense, bright), key (A, C#, Bb), tempo 50-220, bars 2-64, seed";
const FAILED: &str = "audio helper failed to generate the clip";
const TIMEOUT: &str = "audio helper timed out and was stopped; try a shorter text or retry";
const CRASHED: &str = "audio helper exited unexpectedly; it will be restarted on the next request";
const MALFORMED: &str = "audio helper sent an invalid reply and was stopped";
const BAD_OUTPUT: &str = "audio helper produced an unusable file (not a regular WAV within the size and duration caps); it was discarded";
const FILE_FAILED: &str = "audio file operation failed";
const NO_TIMELINE: &str = "audio_envelope needs a native timeline for the tick rate";
const NOT_FOUND: &str = "audio file not found";
const NOT_GRANTED: &str = "path not granted";
const NO_TRACK: &str = "audio_envelope trackId is not an audio track; read ids with audio_list";
const ENVELOPE_LIMIT: &str = "audio_envelope ticks must be 1-100000";

/// One request parameter, already rendered as a JSON value.
#[derive(Clone, Debug, PartialEq)]
pub struct Param {
    pub key: String,
    pub json: String,
}

#[derive(Clone, Debug, PartialEq)]
pub struct GenSpec {
    pub kind: AudioKind,
    pub params: Vec<Param>,
    pub out_path: String,
    pub consent: bool,
    /// Track to add from the generated file (its `path` is filled in here).
    pub add: Option<Box<NewTrack>>,
}

#[derive(Clone, Debug, PartialEq)]
pub enum EnvSource {
    Path(String),
    Track(String),
}

#[derive(Clone, Debug, PartialEq)]
pub struct EnvSpec {
    pub source: EnvSource,
    pub ticks: Option<u32>,
}

/// Helper process handle, budget and test knobs of one MCP session.
#[derive(Default)]
pub struct AudioGen {
    helper: Option<Helper>,
    path: Option<PathBuf>,
    timeout: Option<Duration>,
    requests: u32,
    max_requests: Option<u32>,
    bytes: u64,
    next_id: u64,
}

fn access_error(error: AccessError) -> &'static str {
    match error {
        AccessError::NotGranted => NOT_GRANTED,
        AccessError::NotFound | AccessError::NotRegularFile | AccessError::NotDirectory => {
            NOT_FOUND
        }
        AccessError::InvalidPath => NOT_WAV,
    }
}

fn code_message(code: &str) -> &'static str {
    match code {
        "model_missing" => MODEL_MISSING,
        "bad_params" | "bad_kind" => BAD_PARAMS,
        "too_long" => BAD_OUTPUT,
        _ => FAILED,
    }
}

fn failure_message(failure: HelperFailure) -> &'static str {
    match failure {
        HelperFailure::NotFound => NO_HELPER,
        HelperFailure::Untrusted(message) => message,
        HelperFailure::Spawn => {
            "audio helper could not be started; check that python3 is installed and the helper is executable"
        }
        HelperFailure::Timeout => TIMEOUT,
        HelperFailure::Crashed => CRASHED,
        HelperFailure::Malformed => MALFORMED,
    }
}

struct Reply {
    ok: bool,
    code: String,
}

fn parse_reply(bytes: &[u8], id: u64) -> Option<Reply> {
    let doc = JsonDocument::parse(bytes).ok()?;
    let root = doc.root();
    let reply_id = doc.object_get(root, b"id").and_then(|t| doc.uint(t))?;
    let ok = doc.object_get(root, b"ok").and_then(|t| doc.bool(t))?;
    if reply_id != id {
        return None;
    }
    let code = doc
        .object_get(root, b"code")
        .and_then(|t| doc.decoded_string(t))
        .and_then(|b| String::from_utf8(b).ok())
        .unwrap_or_default();
    Some(Reply { ok, code })
}

impl AudioGen {
    /// Uses `path` as the helper (tests, packaged apps) and, when set, a
    /// shorter per-request timeout than the 120 s / 60 s defaults.
    pub fn configure(&mut self, path: PathBuf, timeout: Option<Duration>) {
        self.helper = None;
        self.path = Some(path);
        self.timeout = timeout;
    }

    /// Lowers the per-session request budget (tests).
    pub fn limit_requests(&mut self, max: u32) {
        self.max_requests = Some(max);
    }

    /// Pid of the running helper, if any.
    pub fn helper_pid(&self) -> Option<u32> {
        self.helper.as_ref().map(Helper::pid)
    }

    fn helper(&mut self) -> Result<&mut Helper, HelperFailure> {
        if self.helper.as_mut().is_some_and(|h| !h.alive()) {
            self.helper = None;
        }
        if self.helper.is_none() {
            let path = match self.path.clone() {
                Some(path) => path,
                None => locate()?,
            };
            self.helper = Some(Helper::spawn(&path)?);
        }
        self.helper.as_mut().ok_or(HelperFailure::Spawn)
    }

    pub(super) fn generate(
        &mut self,
        app: &mut AppDocument,
        policy: &AccessPolicy,
        spec: GenSpec,
    ) -> Result<McpOutcome, &'static str> {
        static COUNTER: AtomicU32 = AtomicU32::new(0);
        if !spec.out_path.ends_with(".wav") || spec.out_path.ends_with("/.wav") {
            return Err(NOT_WAV);
        }
        let target = policy
            .resolve_save_path(&spec.out_path)
            .map_err(access_error)?;
        if spec.add.is_some() {
            let base = document_dir(app).map_err(|_| NEEDS_SAVE)?;
            if !target.starts_with(&base) {
                return Err(OUTSIDE);
            }
        }
        if self.requests >= self.max_requests.unwrap_or(MAX_REQUESTS)
            || self.bytes >= MAX_TOTAL_BYTES
        {
            return Err(BUDGET);
        }
        let existed = target.exists();
        let name = target
            .file_name()
            .and_then(OsStr::to_str)
            .ok_or(FILE_FAILED)?;
        let temp = target.with_file_name(format!(
            ".{name}.vexel-audio-{}-{}.wav",
            std::process::id(),
            COUNTER.fetch_add(1, Ordering::Relaxed)
        ));
        let timeout = match (spec.kind, self.timeout) {
            (_, Some(t)) => t,
            (AudioKind::Voice, None) => VOICE_TIMEOUT,
            _ => OTHER_TIMEOUT,
        };
        self.requests += 1;
        self.next_id += 1;
        let id = self.next_id;
        let line = request_line(id, &spec, &temp)?;
        let outcome = self
            .helper()
            .and_then(|h| h.request(&line, timeout))
            .map_err(|failure| {
                self.helper = None;
                failure_message(failure)
            });
        let remove_temp = || {
            let _ = fs::remove_file(&temp);
        };
        let reply = match outcome {
            Ok(reply) => reply,
            Err(message) => {
                remove_temp();
                return Err(message);
            }
        };
        let Some(parsed) = parse_reply(&reply, id) else {
            self.helper = None; // answered another request or sent garbage
            remove_temp();
            return Err(MALFORMED);
        };
        if !parsed.ok {
            remove_temp();
            return Err(code_message(&parsed.code));
        }
        let (bytes, info) = match checked_output(&temp) {
            Ok(v) => v,
            Err(message) => {
                remove_temp();
                return Err(message);
            }
        };
        self.bytes += bytes;
        if fs::rename(&temp, &target).is_err() {
            remove_temp();
            return Err(FILE_FAILED);
        }
        let millis = info.frames as u64 * 1000 / u64::from(info.rate);
        let target_text = target.to_str().ok_or(FILE_FAILED)?.to_owned();
        let mut track = String::new();
        if let Some(mut add) = spec.add {
            add.path = target_text.clone();
            match super::mcp_audio::apply(app, policy, AudioOp::Add(add)) {
                Ok(McpOutcome::Reply(json)) => {
                    track = format!(",\"track\":{json}");
                }
                Ok(_) => {}
                Err(message) => {
                    if !existed {
                        let _ = fs::remove_file(&target);
                    }
                    return Err(message);
                }
            }
        }
        Ok(McpOutcome::Reply(format!(
            "{{\"ok\":true,\"kind\":\"{}\",\"path\":{},\"durationMs\":{millis},\"bytes\":{bytes},\"sampleRate\":{}{track}}}",
            spec.kind.name(),
            json_string(&target_text),
            info.rate
        )))
    }
}

fn request_line(id: u64, spec: &GenSpec, temp: &Path) -> Result<String, &'static str> {
    let temp = temp.to_str().ok_or(FILE_FAILED)?;
    let params: Vec<String> = spec
        .params
        .iter()
        .map(|p| format!("{}:{}", json_string(&p.key), p.json))
        .collect();
    Ok(format!(
        "{{\"id\":{id},\"kind\":\"{}\",\"params\":{{{}}},\"outPath\":{},\"consent\":{}}}",
        spec.kind.name(),
        params.join(","),
        json_string(temp),
        spec.consent
    ))
}

/// Re-opens the helper's file without following symlinks and checks size,
/// header and duration before it is allowed anywhere near the target.
fn checked_output(path: &Path) -> Result<(u64, audio_codec::Info), &'static str> {
    let meta = fs::symlink_metadata(path).map_err(|_| BAD_OUTPUT)?;
    if !meta.is_file() || meta.len() > MAX_FILE_BYTES {
        return Err(BAD_OUTPUT);
    }
    let bytes = read_file(path).map_err(|_| BAD_OUTPUT)?;
    let info = audio_codec::probe(&bytes).map_err(|_: AudioError| BAD_OUTPUT)?;
    if info.frames as u64 * 1000 / u64::from(info.rate) > MAX_DURATION_MS {
        return Err(BAD_OUTPUT);
    }
    Ok((bytes.len() as u64, info))
}

fn ticks_per_second(app: &AppDocument) -> Option<u32> {
    app.native_timeline_candidate(settings(), EditLimits::default())
        .ok()
        .and_then(|c| c.view().ok().map(|v| v.ticks_per_second()))
}

fn granted_file(
    app: &AppDocument,
    policy: &AccessPolicy,
    input: &str,
) -> Result<PathBuf, &'static str> {
    let requested = if input.starts_with('/') {
        PathBuf::from(input)
    } else {
        document_dir(app)
            .map_err(|_| "audio paths must be absolute unless the document is saved")?
            .join(input)
    };
    let canonical = policy.resolve_existing(&requested).map_err(|_| NOT_FOUND)?;
    if policy.path_allowed(&canonical) {
        Ok(canonical)
    } else {
        Err(NOT_GRANTED)
    }
}

pub(super) fn envelope(
    app: &AppDocument,
    policy: &AccessPolicy,
    spec: EnvSpec,
) -> Result<McpOutcome, &'static str> {
    let tps = ticks_per_second(app).ok_or(NO_TIMELINE)?;
    let limit = match spec.ticks {
        Some(t) if t == 0 || t as usize > MAX_TICKS => return Err(ENVELOPE_LIMIT),
        Some(t) => Some(t as usize),
        None => None,
    };
    let (mut pcm, start_ms, start_tick) = match &spec.source {
        EnvSource::Path(input) => {
            let path = granted_file(app, policy, input)?;
            let bytes = read_file(&path)?;
            let pcm = audio_codec::decode(&bytes).map_err(AudioError::message)?;
            (pcm, 0, 0)
        }
        EnvSource::Track(id) => {
            let track = tracks_of(app)
                .into_iter()
                .find(|t| &t.id == id)
                .ok_or(NO_TRACK)?;
            let mut pcm = load_track(app, policy, &track)
                .map_err(|_| "audio track's file is missing or unreadable; check audio_list")?;
            if let Some(out) = track.trim_out_ms {
                let keep = (u64::from(out) * u64::from(pcm.rate) / 1000) as usize * pcm.channels;
                pcm.samples.truncate(keep);
            }
            (pcm, track.trim_in_ms, track.start_tick)
        }
    };
    pcm.samples.shrink_to_fit();
    let env = audio_envelope::envelope(&pcm, tps, start_ms, limit).ok_or(ENVELOPE_LIMIT)?;
    let millis = pcm.frames() as u64 * 1000 / u64::from(pcm.rate.max(1));
    let values: Vec<String> = env.rms.iter().map(|v| format!("{v:.3}")).collect();
    Ok(McpOutcome::Reply(format!(
        "{{\"tickRate\":{tps},\"startTick\":{start_tick},\"ticks\":{},\"durationMs\":{millis},\"peakRms\":{:.4},\"rms\":[{}]}}",
        env.rms.len(),
        env.peak_rms,
        values.join(",")
    )))
}
