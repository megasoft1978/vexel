pub fn edges(shape: &SceneShape) -> Vec<FlatEdge> {
    let n = shape.points.len();
    (0..n)
        .map(|i| {
            let (a, b) = (shape.points[i], shape.points[(i + 1) % n]);
            FlatEdge {
                x0: a.0,
                y0: a.1,
                x1: b.0,
                y1: b.1,
            }
        })
        .collect()
}

fn prim(
    kind: FilterKind,
    input: FilterInput,
    input2: FilterInput,
    mode: u8,
    rgba: [u8; 4],
    values: &[(usize, f64)],
    merge: &[FilterInput],
) -> FilterPrimitive {
    let mut merge_inputs = [FilterInput::Graphic; 8];
    merge_inputs[..merge.len()].copy_from_slice(merge);
    let mut v = [0.0; 20];
    for (index, value) in values {
        v[*index] = *value;
    }
    FilterPrimitive {
        kind,
        input,
        input2,
        merge_inputs,
        merge_count: merge.len() as u8,
        mode,
        rgba,
        values: v,
        source_offset: 0,
    }
}

