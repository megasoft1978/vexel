//! Flattened geometry of the pattern fixtures, dumped from the C reference
//! (`svg_shape_decode` at the legacy `svgworkbench` build recorded in
//! `rust/fixtures/render-pattern/manifest.json`). Edges are the document-space
//! `doc->edges` slice of each shape; `transform_inverse` is C
//! `shape_stroke_inverse`. Pattern children are the flattened content document
//! C rasterizes into the tile (captured immediately before
//! `raster_shape_render`), in tile space. `inverse` is the C
//! `pattern_inverse` (tile pixels from the shape's local space).
